def lessons(n, s):
    title, gram, writ = s[0], s[1], s[2]
    oral, read = SESS[n]
    out = [{"title": "عرض الوضعية المشكلة الأم + فهم المنطوق: إسماع الخطاب وفهمه", "domain": "فهم المنطوق",
            "hint": "الحصة الأولى: عرض الوضعية الأم ومناقشتها وتحديد المهمات، ثم إسماع الخطاب."}]
    if oral == 3:
        out.append({"title": "فهم المنطوق: تحليل الخطاب", "domain": "فهم المنطوق"})
    out.append({"title": "إنتاج المنطوق: تحقيق مهارة التحدث", "domain": "فهم المنطوق"})
    for i in range(read):
        out.append({"title": f"قراءة ودراسة النص ({i + 1})", "domain": "فهم المكتوب (قراءة ودراسة النص)", "needs_text": True,
                    "hint": "اكتب عنوان النص من الكتاب المدرسي في خانة «السند / عنوان النص»."})
    out += [{"title": f"الظاهرة اللغوية: {g}", "domain": "الظاهرة اللغوية (البناء اللغوي)"} for g in gram]
    out += [{"title": f"إنتاج المكتوب ({i + 1}): {w}", "domain": "إنتاج المكتوب"} for i, w in enumerate(writ)]
    out += [{"title": "إدماج التعلمات وتقويمها (الحصة الأولى)", "domain": "إدماج التعلمات وتقويمها"},
            {"title": "معالجة النقائص والاختلالات (الحصة الثانية)", "domain": "إدماج التعلمات وتقويمها"}]
    return out


def build(n):
    out = []
    for i, s in enumerate(SEQ[n], 1):
        res = {"فهم المنطوق": f"خطابات منطوقة يغلب عليها {MODE[n]} تتناول موضوع «{s[0]}» وتتضمن قواعد الخطاب الشفوي.",
               "فهم المكتوب": f"نصوص متنوعة شعرية ونثرية مشكولة جزئياً يغلب عليها {MODE[n]}." + (f" {s[3]}." if len(s) > 3 else ""),
               "الظاهرة اللغوية": "؛ ".join(s[1]), "الإنتاج الكتابي": "؛ ".join(s[2])}
        out.append({"title": f"المقطع {i:02d}: {s[0]}", "official": {
            "source": SRC.format(n=n), "levels": TERMINAL[n], "resources": res,
            "situation": f"تنتقى الوضعية في سياق المقطع ({s[0]}) وتكون من اهتمامات المتعلم وذات دلالة.",
            "tasks": [f"ينتج خطابات ونصوصاً يغلب عليها {MODE[n]} مشافهة وكتابة", "يرسي الموارد النحوية والصرفية المستهدفة في المقطع", s[2][-1]],
            "criteria": ["اكتساب معارف", "توظيف معارف", "اكتساب قيم و/أو اتخاذ مواقف", "الوجاهة، الاستعمال السليم للغة، الانسجام، الإتقان"]},
            "lessons": lessons(n, s)})
    return out


