def build_level(n: int) -> list[dict]:
    out = []
    for i, (title, dom, res) in enumerate(SEQS[n], start=1):
        f = FIELD[dom]
        lessons = [{"title": "تقديم الوضعية الانطلاقية للمقطع", "domain": dom,
                    "hint": "وضعية مشكلة أم يتطلب حلها تجنيد موارد المقطع؛ تُعرض وتناقش وتُصاغ الفرضيات دون حلها."}]
        lessons += [{"title": r, "domain": dom} for r in res]
        lessons += [
            {"title": "وضعيات الإرساء والإدماج وحل الوضعية الانطلاقية", "domain": dom,
             "hint": "وضعيات مركبة نوعاً ما لإرساء وإدماج موارد المقطع، ثم العودة إلى الوضعية الانطلاقية وحلها."},
            {"title": "التقويم والمعالجة البيداغوجية", "domain": dom,
             "hint": "وضعيات تقويمية تتعلق بموارد المقطع ومعالجة بيداغوجية للنقائص المحتملة."},
        ]
        out.append({
            "title": f"المقطع {i:02d}: {title}",
            "domain": dom,
            "official": {
                "source": SRC.format(n=n),
                "levels": {"الكفاءة الختامية": TERMINAL[n][f], "الكفاءة الشاملة": GLOBAL[n]},
                "resources": {"هيكلة الموارد المعرفية المستهدفة": "؛ ".join(f"{k}) {r}" for k, r in enumerate(res, 1))},
                "situation": "تقديم وضعية انطلاق يتطلب حلّها تجنيد موارد المقطع، مستمدة من الحياة اليومية للمتعلم.",
                "tasks": STRUCTURE,
                "criteria": CRITERIA,
            },
            "lessons": lessons,
        })
    return out


