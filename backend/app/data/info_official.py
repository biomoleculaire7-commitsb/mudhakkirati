def level(n):
    out = []
    for i, (dom, comp, units) in enumerate(D[n], 1):
        lessons = []
        for k, (u, h, res) in enumerate(units, 1):
            lessons.append({"title": f"{k}. {u} ({h})", "domain": dom, "hint": "الموارد: " + "؛ ".join(res)})
        lessons.append({"title": "المشروع الإدماجي والتقويم المرحلي للكفاءة", "domain": dom})
        out.append({"title": f"الميدان {i:02d}: {dom}", "domain": dom, "official": {
            "source": SRC.format(n=n),
            "levels": {"الكفاءة الختامية": comp, "ملمح التخرج من السنة": PROFILE[n]},
            "resources": {"هيكلة تعلمات المقطع": " | ".join(f"{u}: " + "؛ ".join(r) for u, _, r in units)},
            "situation": "طرح وضعية مشكل انطلاقية من واقع المتعلم تتمحور حول موضوع المقطع.",
            "tasks": ["استرجاع المكتسبات القبلية", "وضعيات تعلمية جزئية تطبيقية على الحاسوب", "إنجاز مشروع يدمج الموارد"],
            "criteria": ["اكتساب معارف", "توظيف معارف (إنجاز تطبيقي سليم على الحاسوب)", "اكتساب قيم و/أو اتخاذ مواقف (الاستعمال الآمن والمسؤول)"]},
            "lessons": lessons})
    return out


