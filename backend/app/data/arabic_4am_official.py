def lessons_for(s: dict) -> list[dict]:
    rh = s["rhetoric"]
    out = [
        {"title": "عرض الوضعية المشكلة الأم + فهم المنطوق: إسماع الخطاب وفهمه", "domain": "فهم المنطوق",
         "hint": "الحصة الأولى من الأسبوع الأول: عرض الوضعية الأم ومناقشتها وتحديد المهمات، ثم إسماع الخطاب."},
        {"title": "فهم المنطوق وإنتاجه: الحصة الثانية (إنتاج المنطوق)", "domain": "فهم المنطوق",
         "hint": "مهارة التحدث والتعبير عن الفهم في سياق تفاعلي."},
    ]
    for i in range(3):
        rhet = f" — الظاهرة البلاغية: {rh[i]}" if i < len(rh) else ""
        out.append({"title": f"قراءة ودراسة النص ({i + 1}){rhet}", "domain": "فهم المكتوب (قراءة ودراسة النص)",
                    "hint": "اكتب عنوان النص من الكتاب المدرسي في خانة «السند / عنوان النص».", "needs_text": True})
    for g in s["grammar"]:
        out.append({"title": f"الظاهرة اللغوية: {g}", "domain": "الظاهرة اللغوية (البناء اللغوي)"})
    for i, w in enumerate(s["writing"]):
        out.append({"title": f"إنتاج المكتوب ({i + 1}): {w}", "domain": "إنتاج المكتوب"})
    out += [
        {"title": "إدماج التعلمات وتقويمها (الحصة الأولى)", "domain": "إدماج التعلمات وتقويمها",
         "hint": "اقتراح وضعية إدماج لتقويم مستوى الكفاءة خلال المقطع وتصحيحها بشبكة المعايير."},
        {"title": "معالجة النقائص والاختلالات (الحصة الثانية)", "domain": "إدماج التعلمات وتقويمها",
         "hint": "معالجة النقائص وفق المعايير: الوجاهة والملاءمة، الاستعمال السليم للغة، الانسجام والترابط، الجودة والإبداع."},
    ]
    return out


